def tr(key: str, **kwargs) -> str:
    """
    Translate a string key according to the current Anki user language.
    Falls back gracefully: exact code -> base code -> en -> fr -> key.
    Supports string formatting via kwargs.
    """
    lang_code = get_anki_lang()

    # 1. Exact match (e.g. 'zh_CN', 'pt_BR')
    dict_match = TRANSLATIONS.get(lang_code)

    # 2. Base match (e.g. 'fr' from 'fr_FR' or 'fr-CA')
    if dict_match is None and "_" in lang_code:
        base_lang = lang_code.split("_")[0]
        dict_match = TRANSLATIONS.get(base_lang)
    elif dict_match is None and "-" in lang_code:
        base_lang = lang_code.split("-")[0]
        dict_match = TRANSLATIONS.get(base_lang)

    # 3. Fallback to English, then French
    if dict_match is None or key not in dict_match:
        dict_match = TRANSLATIONS.get("en", {})
    if key not in dict_match:
        dict_match = TRANSLATIONS.get("fr", {})

    template = dict_match.get(key, key)
    if kwargs:
        try:
            return template.format(**kwargs)
        except Exception:
            return template
    return template
