from typing import Optional

def get_anki_lang() -> str:
    """Detect current Anki language code (e.g. 'fr', 'en_GB', 'zh_CN', 'es', etc.)."""
    try:
        from aqt import mw
        if mw and hasattr(mw, "pm") and mw.pm and hasattr(mw.pm, "meta"):
            lang = mw.pm.meta.get("lang")
            if lang:
                return lang
    except Exception:
        pass

    try:
        import anki.lang
        if hasattr(anki.lang, "current_lang"):
            return str(anki.lang.current_lang)
    except Exception:
        pass

    return "en"


